export type Language = "en" | "si";

export const LANGUAGE_COOKIE = "brakmasra_lang";

export function parseLanguage(value: string | null | undefined): Language {
  return value === "si" ? "si" : "en";
}

const MONTHS: Record<Language, string[]> = {
  en: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
  si: ["ජනවාරි", "පෙබරවාරි", "මාර්තු", "අප්‍රේල්", "මැයි", "ජූනි", "ජූලි", "අගෝස්තු", "සැප්තැම්බර්", "ඔක්තෝබර්", "නොවැම්බර්", "දෙසැම්බර්"],
};

/**
 * Formats a date in UTC without Intl locale data, which many browsers lack
 * for Sinhala; this keeps server and browser output identical.
 */
export function formatDate(value: string | Date, lang: Language, { day = true }: { day?: boolean } = {}) {
  const date = new Date(value);
  const month = MONTHS[lang][date.getUTCMonth()];
  const year = date.getUTCFullYear();
  if (lang === "si") return day ? `${year} ${month} ${date.getUTCDate()}` : `${year} ${month}`;
  return day ? `${month} ${date.getUTCDate()}, ${year}` : `${month} ${year}`;
}

